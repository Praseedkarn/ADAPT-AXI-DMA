class axi4_transaction extends uvm_sequence_item;

    //============================================================
    // AXI4 Transaction Type
    //============================================================

    typedef enum {
        AXI4_READ,
        AXI4_WRITE
    } axi4_cmd_e;

    axi4_cmd_e cmd;

    //============================================================
    // Address Channel
    //============================================================

    bit [31:0] addr;
    bit [7:0]  len;
    bit [2:0]  size;
    bit [1:0]  burst;

    //============================================================
    // Data
    //============================================================

    bit [31:0] data;
    bit [3:0]  strb;

    //============================================================
    // Write Data
    //============================================================

    bit last;

    //============================================================
    // Response
    //============================================================

    bit [31:0] read_data;
    bit [1:0]  resp;

    //============================================================
    // Constructor
    //============================================================

    function new(string name = "axi4_transaction");
        super.new(name);
    endfunction

    //============================================================
    // UVM Factory Registration
    //============================================================

    `uvm_object_utils(axi4_transaction)

endclass